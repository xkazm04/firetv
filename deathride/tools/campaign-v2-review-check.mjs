import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {resolve} from 'node:path';
import {pathToFileURL,fileURLToPath} from 'node:url';
import {mkdir,writeFile,readFile,access} from 'node:fs/promises';
const output=resolve(process.env.CAMPAIGN_REVIEW_OUTPUT||'evidence/campaign/design-v2/review-browser');
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_EXECUTABLE||'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const url=pathToFileURL(resolve('campaign/design-v2/index.html')).href;
try {
 const context=await browser.newContext({viewport:{width:1440,height:1080}});
 const page=await context.newPage(), errors=[],remote=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(/^https?:/.test(r.url()))remote.push(r.url())});
 await page.goto(url);
 assert.equal(await page.locator('article.card[data-direction]').count(),8);
 const original=(await readFile('campaign/OWNER-CAMPAIGN-CHOICE.md','utf8')).split("## The owner's words")[1].split('## Host reading')[0].trim().replace(/^> /,'');
 assert.equal((await page.locator('blockquote').textContent()).trim(),original,'Owner plot remains verbatim');
 assert.equal(await page.locator('#story-sheet tbody tr').count(),35);
 assert.equal(await page.locator('input[type=radio]:checked').count(),0,'No inferred owner decisions');
 for(const href of await page.locator('a[href],link[href]').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('href'))))await access(fileURLToPath(new URL(href,url)));
 await page.screenshot({path:resolve(output,'desktop-light.png')});
 await page.getByRole('button',{name:'Refresh Markdown'}).click();
 assert.equal((await page.locator('#export').inputValue()).match(/Not reviewed/g).length,8);
 const first=page.locator('article.card[data-direction]').first();
 await first.getByRole('radio',{name:'Keep',exact:true}).check();
 await first.locator('textarea').fill('A | pipe \\ and <markup>\nsecond line');
 await page.locator('#theme').selectOption('dark');
 await page.getByRole('button',{name:'Copy Markdown',exact:true}).click();
 const markdown=await page.locator('#export').inputValue();
 assert.ok(markdown.includes('| Category / direction | Pick | Samples | Owner note |'));
 assert.ok(markdown.includes('A &#124; pipe &#92; and &lt;markup&gt;<br>second line'));
 assert.ok(markdown.includes('| Keep |'));
 await page.reload();
 assert.equal(await first.getByRole('radio',{name:'Keep',exact:true}).isChecked(),true);
 assert.ok((await first.locator('textarea').inputValue()).includes('second line'));
 for(const img of await page.locator('img').all())await img.evaluate(el=>el.decode());
 await page.screenshot({path:resolve(output,'desktop.png')});
 await page.setViewportSize({width:667,height:740});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:resolve(output,'mobile.png')});
 assert.deepEqual(errors,[]);assert.deepEqual(remote,[]);
 const blocked=await browser.newContext();const noStore=await blocked.newPage();
 await noStore.addInitScript(()=>Object.defineProperty(window,'localStorage',{get(){throw new Error('disabled')}}));
 await noStore.goto(url);
 assert.ok((await noStore.locator('#status').innerText()).includes('storage unavailable'));
 await noStore.locator('article.card[data-direction]').first().getByRole('radio',{name:'Maybe',exact:true}).check();
 await noStore.getByRole('button',{name:'Refresh Markdown'}).click();
 assert.ok((await noStore.locator('#export').inputValue()).includes('| Maybe |'));
 await writeFile(resolve(output,'result.json'),JSON.stringify({pass:true,url,cards:8,checks:['file URL only','owner quote verbatim','35 implemented story beats','no inferred choices','Keep Maybe Reject per decision','notes survive reload','escaped Markdown matches audio table format','copy with selectable fallback','dark theme','667px layout','all plots load','all local links exist','storage-denied export'],errors,remote},null,2));
 console.log('Offline owner review PASS');
} finally {await browser.close()}
